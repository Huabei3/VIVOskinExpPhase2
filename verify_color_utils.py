fails = 0
total = 0


def check(name, got, want, atol):
    global fails, total
    total += 1
    ok = np.allclose(got, want, atol=atol, rtol=0)
    if not ok:
        fails += 1
        print(f"[FAIL] {name}: got={np.asarray(got)} want={np.asarray(want)}")
    return ok


